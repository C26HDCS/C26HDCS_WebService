CREATE TABLE TB_DEVICE (DEVICE_ID BIGINT PRIMARY KEY, DEVICE_NAME VARCHAR(100));
CREATE TABLE TB_USER (USER_ID VARCHAR(50) PRIMARY KEY);
CREATE TABLE TB_LOG (
    ID SERIAL PRIMARY KEY,
    DEVICE_ID BIGINT NOT NULL REFERENCES TB_DEVICE(DEVICE_ID),
    LEVEL VARCHAR(10) NOT NULL,
    MESSAGE VARCHAR(1000) NOT NULL,
    REG_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE TB_EVENT (
    ID SERIAL PRIMARY KEY,
    USER_ID VARCHAR(50) REFERENCES TB_USER(USER_ID) ON DELETE SET NULL,
    ACTOR_USER_ID VARCHAR(50),
    RECORD_KEY VARCHAR(36) UNIQUE,
    EVENT_TYPE VARCHAR(30) NOT NULL,
    MESSAGE VARCHAR(1000) NOT NULL,
    REG_DT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
