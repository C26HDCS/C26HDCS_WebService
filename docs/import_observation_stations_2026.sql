CREATE TEMP VIEW station_import_plan AS
SELECT i.*, s.station_id,
       CASE
           WHEN EXISTS (
               SELECT FROM public.tb_device d
               JOIN station_import_ka_device k USING (device_id)
               WHERE d.station_id = s.station_id
           ) THEN 'KA_PROTECTED'
           WHEN s.station_id IS NULL THEN 'INSERT'
           WHEN (s.name, s.address, s.lat, s.lng) IS DISTINCT FROM (i.name, i.address, i.lat, i.lng)
               THEN 'UPDATE'
           ELSE 'UNCHANGED'
       END AS action
FROM station_import_source i
LEFT JOIN public.tb_observation_station s ON btrim(s.obs_code) = i.obs_code;

SELECT kind, action, count(*) AS station_count
FROM station_import_plan GROUP BY kind, action ORDER BY kind, action;

SELECT i.group_name, g.group_id, g.use_yn,
       CASE WHEN g.group_id IS NULL THEN 'INSERT' ELSE 'REUSE' END AS action
FROM (SELECT DISTINCT group_name FROM station_import_source) i
LEFT JOIN public.tb_device_group g ON btrim(g.group_name) = i.group_name
ORDER BY i.group_name;

SELECT obs_code, count(*) AS duplicate_matches
FROM station_import_plan GROUP BY obs_code HAVING count(*) > 1;

SELECT obs_code, station_id, name
FROM station_import_plan WHERE action = 'KA_PROTECTED' ORDER BY obs_code;

SELECT s.station_id, s.obs_code, s.name,
       EXISTS (SELECT FROM public.tb_device d WHERE d.station_id = s.station_id) AS linked_device,
       EXISTS (
           SELECT FROM public.tb_device d JOIN station_import_ka_device k USING (device_id)
           WHERE d.station_id = s.station_id
       ) AS ka_protected
FROM public.tb_observation_station s
WHERE NOT EXISTS (SELECT FROM station_import_source i WHERE i.obs_code = btrim(s.obs_code))
ORDER BY s.station_id;

DO $apply$
DECLARE
    delete_ids bigint[];
    added_groups integer;
    added_stations integer;
    updated_stations integer;
    changed_devices integer;
    deleted_stations integer;
BEGIN
    IF NOT (SELECT apply_changes FROM station_import_options) THEN
        RAISE NOTICE 'Preview only. No permanent tables changed.';
        RETURN;
    END IF;

    IF EXISTS (SELECT FROM station_import_plan GROUP BY obs_code HAVING count(*) > 1)
       OR EXISTS (
           SELECT FROM public.tb_device_group g
           JOIN (SELECT DISTINCT group_name FROM station_import_source) i
             ON btrim(g.group_name) = i.group_name
           GROUP BY i.group_name HAVING count(*) > 1
       ) THEN
        RAISE EXCEPTION 'Resolve duplicate observation codes or group names before importing.';
    END IF;

    INSERT INTO public.tb_device_group (group_name)
    SELECT DISTINCT i.group_name
    FROM station_import_source i
    WHERE NOT EXISTS (SELECT FROM public.tb_device_group g WHERE btrim(g.group_name) = i.group_name);
    GET DIAGNOSTICS added_groups = ROW_COUNT;

    UPDATE public.tb_observation_station s
    SET name = p.name, address = p.address, lat = p.lat, lng = p.lng
    FROM station_import_plan p
    WHERE p.action = 'UPDATE' AND p.station_id = s.station_id;
    GET DIAGNOSTICS updated_stations = ROW_COUNT;

    INSERT INTO public.tb_observation_station (obs_code, name, address, lat, lng)
    SELECT obs_code, name, address, lat, lng
    FROM station_import_plan WHERE action = 'INSERT';
    GET DIAGNOSTICS added_stations = ROW_COUNT;

    UPDATE public.tb_device d
    SET group_id = g.group_id
    FROM station_import_plan p
    JOIN public.tb_device_group g ON btrim(g.group_name) = p.group_name
    WHERE p.station_id = d.station_id AND p.action <> 'KA_PROTECTED'
      AND g.use_yn = 'Y' AND d.group_id IS DISTINCT FROM g.group_id;
    GET DIAGNOSTICS changed_devices = ROW_COUNT;

    SELECT approved_delete_ids INTO delete_ids FROM station_import_options;
    IF cardinality(delete_ids) > 0 AND EXISTS (
        SELECT FROM pg_constraint
        WHERE contype = 'f' AND confrelid = 'public.tb_observation_station'::regclass
          AND confdeltype IN ('c', 'n', 'd')
    ) THEN
        RAISE EXCEPTION 'Review foreign keys with automatic delete actions before deleting stations.';
    END IF;

    deleted_stations := 0;
    IF cardinality(delete_ids) > 0 THEN
        DELETE FROM public.tb_observation_station s
        WHERE s.station_id = ANY (delete_ids)
          AND NOT EXISTS (SELECT FROM station_import_source i WHERE i.obs_code = btrim(s.obs_code))
          AND NOT EXISTS (SELECT FROM public.tb_device d WHERE d.station_id = s.station_id);
        GET DIAGNOSTICS deleted_stations = ROW_COUNT;

        IF deleted_stations <> cardinality(delete_ids) THEN
            RAISE EXCEPTION 'Some delete IDs are missing, duplicated, in the import, or linked to devices.';
        END IF;
    END IF;

    RAISE NOTICE 'Groups added %, stations added %, stations updated %, device groups changed %, stations deleted %',
        added_groups, added_stations, updated_stations, changed_devices, deleted_stations;
END
$apply$;

